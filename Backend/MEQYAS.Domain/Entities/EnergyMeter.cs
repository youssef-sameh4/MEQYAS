using MEQYAS.Domain.Enums;

namespace MEQYAS.Domain.Entities;

//ده كلاس تاتميتلر
/// <summary>
/// Represents a smart energy meter installed within a factory to measure consumption.
/// </summary>
public class EnergyMeter
{
    /// <summary>
    /// Gets or sets the unique identifier for the energy meter.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// Gets or sets the unique identifier of the factory where this meter is installed.
    /// </summary>
    public Guid FactoryId { get; set; }

    /// <summary>
    /// Gets or sets the display name or label of the energy meter.
    /// </summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the unique code assigned to the energy meter.
    /// </summary>
    public string Code { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the meter type (e.g., Main, SubMeter).
    /// </summary>
    public MeterType MeterType { get; set; }

    /// <summary>
    /// Gets or sets the measurement unit used by the meter (e.g., kWh).
    /// </summary>
    public string Unit { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets a value indicating whether the energy meter is currently active.
    /// </summary>
    public bool IsActive { get; set; }

    /// <summary>
    /// Gets or sets the date and time in UTC when the energy meter was created.
    /// </summary>
    public DateTime CreatedAtUtc { get; set; }

    // Navigation Properties

    /// <summary>
    /// Gets or sets the factory that owns this energy meter.
    /// </summary>
    public Factory Factory { get; set; } = null!;

    /// <summary>
    /// Gets or sets the collection of energy readings recorded by this meter.
    /// </summary>
    public ICollection<EnergyReading> EnergyReadings { get; set; }
        = new List<EnergyReading>();

    /// <summary>
    /// Gets or sets the collection of alerts generated by or associated with this meter.
    /// </summary>
    public ICollection<EnergyAlert> EnergyAlerts { get; set; }
        = new List<EnergyAlert>();
}